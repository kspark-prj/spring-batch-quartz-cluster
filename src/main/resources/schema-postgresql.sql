CREATE TABLE IF NOT EXISTS BATCH_JOB_INSTANCE  (
    JOB_INSTANCE_ID BIGINT NOT NULL PRIMARY KEY,
    VERSION BIGINT,
    JOB_NAME VARCHAR(100) NOT NULL,
    JOB_KEY VARCHAR(32) NOT NULL,
    CONSTRAINT JOB_INST_UN UNIQUE (JOB_NAME, JOB_KEY)
);

COMMENT ON TABLE BATCH_JOB_INSTANCE IS '스프링 배치 잡(Job)의 고유 인스턴스 정보를 관리하는 테이블';
COMMENT ON COLUMN BATCH_JOB_INSTANCE.JOB_INSTANCE_ID IS '잡 인스턴스 고유 ID (PK)';
COMMENT ON COLUMN BATCH_JOB_INSTANCE.VERSION IS '낙관적 락을 위한 버전 관리 컬럼';
COMMENT ON COLUMN BATCH_JOB_INSTANCE.JOB_NAME IS '실행된 잡의 이름';
COMMENT ON COLUMN BATCH_JOB_INSTANCE.JOB_KEY IS '잡 파라미터를 해시화하여 중복 실행을 막기 위한 고유 키';


CREATE TABLE IF NOT EXISTS BATCH_JOB_EXECUTION  (
    JOB_EXECUTION_ID BIGINT NOT NULL PRIMARY KEY,
    VERSION BIGINT,
    JOB_INSTANCE_ID BIGINT NOT NULL,
    CREATE_TIME TIMESTAMP NOT NULL,
    START_TIME TIMESTAMP DEFAULT NULL,
    END_TIME TIMESTAMP DEFAULT NULL,
    STATUS VARCHAR(10),
    EXIT_CODE VARCHAR(2500),
    EXIT_MESSAGE VARCHAR(2500),
    LAST_UPDATED TIMESTAMP,
    CONSTRAINT JOB_INST_EXEC_FK FOREIGN KEY (JOB_INSTANCE_ID)
    REFERENCES BATCH_JOB_INSTANCE(JOB_INSTANCE_ID)
);

COMMENT ON TABLE BATCH_JOB_EXECUTION IS '잡(Job)이 실제로 시도되고 실행된 이력을 관리하는 테이블';
COMMENT ON COLUMN BATCH_JOB_EXECUTION.JOB_EXECUTION_ID IS '잡 실행 고유 ID (PK)';
COMMENT ON COLUMN BATCH_JOB_EXECUTION.VERSION IS '낙관적 락을 위한 버전 관리 컬럼';
COMMENT ON COLUMN BATCH_JOB_EXECUTION.JOB_INSTANCE_ID IS '연관된 잡 인스턴스 ID (FK)';
COMMENT ON COLUMN BATCH_JOB_EXECUTION.CREATE_TIME IS '잡 실행이 생성된 시간';
COMMENT ON COLUMN BATCH_JOB_EXECUTION.START_TIME IS '잡 실행이 시작된 시간';
COMMENT ON COLUMN BATCH_JOB_EXECUTION.END_TIME IS '잡 실행이 완료된 시간';
COMMENT ON COLUMN BATCH_JOB_EXECUTION.STATUS IS '잡 실행 상태 (COMPLETED, FAILED, STARTED 등)';
COMMENT ON COLUMN BATCH_JOB_EXECUTION.EXIT_CODE IS '잡 종료 코드';
COMMENT ON COLUMN BATCH_JOB_EXECUTION.EXIT_MESSAGE IS '잡 실패 시 에러 메시지 상세 내용';
COMMENT ON COLUMN BATCH_JOB_EXECUTION.LAST_UPDATED IS '잡 실행 정보가 마지막으로 갱신된 시간';


CREATE TABLE IF NOT EXISTS BATCH_JOB_EXECUTION_PARAMS  (
    JOB_EXECUTION_ID BIGINT NOT NULL,
    PARAMETER_NAME VARCHAR(100) NOT NULL,
    PARAMETER_TYPE VARCHAR(100) NOT NULL,
    PARAMETER_VALUE VARCHAR(2500),
    IDENTIFYING CHAR(1) NOT NULL,
    CONSTRAINT JOB_EXEC_PARAMS_FK FOREIGN KEY (JOB_EXECUTION_ID)
    REFERENCES BATCH_JOB_EXECUTION(JOB_EXECUTION_ID)
);

COMMENT ON TABLE BATCH_JOB_EXECUTION_PARAMS IS '잡(Job) 실행 시 전달된 파라미터(JobParameters) 정보를 저장하는 테이블';
COMMENT ON COLUMN BATCH_JOB_EXECUTION_PARAMS.JOB_EXECUTION_ID IS '연관된 잡 실행 ID (FK)';
COMMENT ON COLUMN BATCH_JOB_EXECUTION_PARAMS.PARAMETER_NAME IS '파라미터 이름';
COMMENT ON COLUMN BATCH_JOB_EXECUTION_PARAMS.PARAMETER_TYPE IS '파라미터 데이터 타입';
COMMENT ON COLUMN BATCH_JOB_EXECUTION_PARAMS.PARAMETER_VALUE IS '파라미터 값';
COMMENT ON COLUMN BATCH_JOB_EXECUTION_PARAMS.IDENTIFYING IS '인스턴스 식별에 사용되는 파라미터 여부 (Y/N)';


CREATE TABLE IF NOT EXISTS BATCH_STEP_EXECUTION  (
    STEP_EXECUTION_ID BIGINT NOT NULL PRIMARY KEY,
    VERSION BIGINT NOT NULL,
    STEP_NAME VARCHAR(100) NOT NULL,
    JOB_EXECUTION_ID BIGINT NOT NULL,
    CREATE_TIME TIMESTAMP NOT NULL,
    START_TIME TIMESTAMP DEFAULT NULL,
    END_TIME TIMESTAMP DEFAULT NULL,
    STATUS VARCHAR(10),
    COMMIT_COUNT BIGINT,
    READ_COUNT BIGINT,
    FILTER_COUNT BIGINT,
    WRITE_COUNT BIGINT,
    READ_SKIP_COUNT BIGINT,
    WRITE_SKIP_COUNT BIGINT,
    PROCESS_SKIP_COUNT BIGINT,
    ROLLBACK_COUNT BIGINT,
    EXIT_CODE VARCHAR(2500),
    EXIT_MESSAGE VARCHAR(2500),
    LAST_UPDATED TIMESTAMP,
    CONSTRAINT JOB_EXEC_STEP_FK FOREIGN KEY (JOB_EXECUTION_ID)
    REFERENCES BATCH_JOB_EXECUTION(JOB_EXECUTION_ID)
);

COMMENT ON TABLE BATCH_STEP_EXECUTION IS '잡 내부의 각 스텝(Step) 단위 실행 이력과 통계 정보를 관리하는 테이블';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.STEP_EXECUTION_ID IS '스텝 실행 고유 ID (PK)';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.VERSION IS '낙관적 락을 위한 버전 관리 컬럼';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.STEP_NAME IS '스텝 이름';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.JOB_EXECUTION_ID IS '연관된 잡 실행 ID (FK)';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.CREATE_TIME IS '스텝 실행이 생성된 시간';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.START_TIME IS '스텝 실행이 시작된 시간';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.END_TIME IS '스텝 실행이 완료된 시간';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.STATUS IS '스텝 실행 상태';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.COMMIT_COUNT IS '트랜잭션 커밋 횟수';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.READ_COUNT IS '아이템 읽기 성공 횟수';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.FILTER_COUNT IS '필터링된 아이템 횟수';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.WRITE_COUNT IS '아이템 쓰기 성공 횟수';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.READ_SKIP_COUNT IS '읽기 스킵 횟수';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.WRITE_SKIP_COUNT IS '쓰기 스킵 횟수';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.PROCESS_SKIP_COUNT IS '프로세스 스킵 횟수';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.ROLLBACK_COUNT IS '트랜잭션 롤백 횟수';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.EXIT_CODE IS '스텝 종료 코드';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.EXIT_MESSAGE IS '스텝 실패 시 에러 메시지 상세 내용';
COMMENT ON COLUMN BATCH_STEP_EXECUTION.LAST_UPDATED IS '스텝 실행 정보가 마지막으로 갱신된 시간';


CREATE TABLE IF NOT EXISTS BATCH_STEP_EXECUTION_CONTEXT  (
    STEP_EXECUTION_ID BIGINT NOT NULL PRIMARY KEY,
    SHORT_CONTEXT VARCHAR(2500) NOT NULL,
    SERIALIZED_CONTEXT TEXT,
    CONSTRAINT STEP_EXEC_CTX_FK FOREIGN KEY (STEP_EXECUTION_ID)
    REFERENCES BATCH_STEP_EXECUTION(STEP_EXECUTION_ID)
);

COMMENT ON TABLE BATCH_STEP_EXECUTION_CONTEXT IS '각 스텝(Step)의 실행 중 유지해야 할 데이터(ExecutionContext)를 저장하는 테이블';
COMMENT ON COLUMN BATCH_STEP_EXECUTION_CONTEXT.STEP_EXECUTION_ID IS '연관된 스텝 실행 ID (PK/FK)';
COMMENT ON COLUMN BATCH_STEP_EXECUTION_CONTEXT.SHORT_CONTEXT IS '컨텍스트 데이터의 문자열 형태 표현';
COMMENT ON COLUMN BATCH_STEP_EXECUTION_CONTEXT.SERIALIZED_CONTEXT IS '직렬화된 상세 컨텍스트 데이터';


CREATE TABLE IF NOT EXISTS BATCH_JOB_EXECUTION_CONTEXT  (
    JOB_EXECUTION_ID BIGINT NOT NULL PRIMARY KEY,
    SHORT_CONTEXT VARCHAR(2500) NOT NULL,
    SERIALIZED_CONTEXT TEXT,
    CONSTRAINT JOB_EXEC_CTX_FK FOREIGN KEY (JOB_EXECUTION_ID)
    REFERENCES BATCH_JOB_EXECUTION(JOB_EXECUTION_ID)
);

COMMENT ON TABLE BATCH_JOB_EXECUTION_CONTEXT IS '잡(Job) 전체 범위에서 유지해야 할 데이터(ExecutionContext)를 저장하는 테이블';
COMMENT ON COLUMN BATCH_JOB_EXECUTION_CONTEXT.JOB_EXECUTION_ID IS '연관된 잡 실행 ID (PK/FK)';
COMMENT ON COLUMN BATCH_JOB_EXECUTION_CONTEXT.SHORT_CONTEXT IS '컨텍스트 데이터의 문자열 형태 표현';
COMMENT ON COLUMN BATCH_JOB_EXECUTION_CONTEXT.SERIALIZED_CONTEXT IS '직렬화된 상세 컨텍스트 데이터';


