CREATE TABLE IF NOT EXISTS QRTZ_JOB_DETAILS (
    SCHED_NAME VARCHAR(120) NOT NULL,
    JOB_NAME VARCHAR(200) NOT NULL,
    JOB_GROUP VARCHAR(200) NOT NULL,
    DESCRIPTION VARCHAR(250) NULL,
    JOB_CLASS_NAME VARCHAR(250) NOT NULL,
    IS_DURABLE BOOL NOT NULL,
    IS_NONCONCURRENT BOOL NOT NULL,
    IS_UPDATE_DATA BOOL NOT NULL,
    REQUESTS_RECOVERY BOOL NOT NULL,
    JOB_DATA BYTEA NULL,
    PRIMARY KEY (SCHED_NAME, JOB_NAME, JOB_GROUP)
);

COMMENT ON TABLE QRTZ_JOB_DETAILS IS '쿼츠(Quartz) 스케줄러가 실행할 잡(Job)의 상세 정의를 저장하는 테이블';
COMMENT ON COLUMN QRTZ_JOB_DETAILS.SCHED_NAME IS '스케줄러 이름';
COMMENT ON COLUMN QRTZ_JOB_DETAILS.JOB_NAME IS '잡 이름';
COMMENT ON COLUMN QRTZ_JOB_DETAILS.JOB_GROUP IS '잡 그룹 이름';
COMMENT ON COLUMN QRTZ_JOB_DETAILS.DESCRIPTION IS '잡 설명';
COMMENT ON COLUMN QRTZ_JOB_DETAILS.JOB_CLASS_NAME IS '실행될 Job 클래스의 전체 경로(FQN)';
COMMENT ON COLUMN QRTZ_JOB_DETAILS.IS_DURABLE IS '트리거 없이도 영구 보존될지 여부';
COMMENT ON COLUMN QRTZ_JOB_DETAILS.IS_NONCONCURRENT IS '동시 실행을 막을지 여부 (Stateful)';
COMMENT ON COLUMN QRTZ_JOB_DETAILS.IS_UPDATE_DATA IS 'JobDataMap 변경 사항 업데이트 여부';
COMMENT ON COLUMN QRTZ_JOB_DETAILS.REQUESTS_RECOVERY IS '복구(Recovery) 대상 잡 여부';
COMMENT ON COLUMN QRTZ_JOB_DETAILS.JOB_DATA IS '잡 실행 시 전달할 직렬화된 데이터(JobDataMap)';


CREATE TABLE IF NOT EXISTS QRTZ_TRIGGERS (
    SCHED_NAME VARCHAR(120) NOT NULL,
    TRIGGER_NAME VARCHAR(200) NOT NULL,
    TRIGGER_GROUP VARCHAR(200) NOT NULL,
    JOB_NAME VARCHAR(200) NOT NULL,
    JOB_GROUP VARCHAR(200) NOT NULL,
    DESCRIPTION VARCHAR(250) NULL,
    NEXT_FIRE_TIME BIGINT NULL,
    PREV_FIRE_TIME BIGINT NULL,
    PRIORITY INTEGER NULL,
    TRIGGER_STATE VARCHAR(16) NOT NULL,
    TRIGGER_TYPE VARCHAR(8) NOT NULL,
    START_TIME BIGINT NOT NULL,
    END_TIME BIGINT NULL,
    CALENDAR_NAME VARCHAR(200) NULL,
    MISFIRE_INSTR SMALLINT NULL,
    JOB_DATA BYTEA NULL,
    PRIMARY KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP),
    FOREIGN KEY (SCHED_NAME, JOB_NAME, JOB_GROUP)
        REFERENCES QRTZ_JOB_DETAILS(SCHED_NAME, JOB_NAME, JOB_GROUP)
);

COMMENT ON TABLE QRTZ_TRIGGERS IS '쿼츠(Quartz) 잡을 실행하기 위한 트리거(Trigger) 정보를 관리하는 테이블';
COMMENT ON COLUMN QRTZ_TRIGGERS.SCHED_NAME IS '스케줄러 이름';
COMMENT ON COLUMN QRTZ_TRIGGERS.TRIGGER_NAME IS '트리거 이름';
COMMENT ON COLUMN QRTZ_TRIGGERS.TRIGGER_GROUP IS '트리거 그룹 이름';
COMMENT ON COLUMN QRTZ_TRIGGERS.JOB_NAME IS '연관된 잡 이름';
COMMENT ON COLUMN QRTZ_TRIGGERS.JOB_GROUP IS '연관된 잡 그룹 이름';
COMMENT ON COLUMN QRTZ_TRIGGERS.DESCRIPTION IS '트리거 설명';
COMMENT ON COLUMN QRTZ_TRIGGERS.NEXT_FIRE_TIME IS '다음 실행 예정 시각 (밀리초)';
COMMENT ON COLUMN QRTZ_TRIGGERS.PREV_FIRE_TIME IS '이전 실행 시각 (밀리초)';
COMMENT ON COLUMN QRTZ_TRIGGERS.PRIORITY IS '트리거 우선순위';
COMMENT ON COLUMN QRTZ_TRIGGERS.TRIGGER_STATE IS '트리거 상태 (WAITING, PAUSED, ACQUIRED, COMPLETE 등)';
COMMENT ON COLUMN QRTZ_TRIGGERS.TRIGGER_TYPE IS '트리거 타입 (CRON, SIMPLE 등)';
COMMENT ON COLUMN QRTZ_TRIGGERS.START_TIME IS '트리거 시작 시각';
COMMENT ON COLUMN QRTZ_TRIGGERS.END_TIME IS '트리거 종료 시각';
COMMENT ON COLUMN QRTZ_TRIGGERS.CALENDAR_NAME IS '적용된 캘린더 이름';
COMMENT ON COLUMN QRTZ_TRIGGERS.MISFIRE_INSTR IS '미스파이어(Misfire) 발생 시 처리 정책 지시자';
COMMENT ON COLUMN QRTZ_TRIGGERS.JOB_DATA IS '트리거에 종속된 직렬화 데이터';


